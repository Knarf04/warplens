"""Build and archive probe artifacts without relying on paths on the rental machine.

PTX is extracted from the exact executable, never regenerated by a second compilation.
Native-only programs carry a separately built PTX companion; that is a reproducible
simulator input, not proof of which PTX the native compiler's backend consumed.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
import hashlib
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys

SCHEMA = "warplens.probe-build.v1"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def extracted_ptx(binary: Path) -> list[str]:
    """Read uncompressed CUDA PTX records from a little-endian ELF64 executable.

    No CUDA library or tool is loaded. Malformed containers and compressed PTX fail
    explicitly; build the fixture with nvcc --no-compress. Native-only ELF returns [].
    """
    data = Path(binary).read_bytes()
    if len(data) < 64 or data[:6] != b"\x7fELF\x02\x01":
        raise ValueError(f"not a little-endian ELF64 executable: {binary}")
    shoff = struct.unpack_from("<Q", data, 40)[0]
    size, count, names = struct.unpack_from("<HHH", data, 58)
    if size < 64 or not count or names >= count or shoff + count * size > len(data):
        raise ValueError("invalid ELF section table")

    def section(index):
        at = shoff + index * size
        name = struct.unpack_from("<I", data, at)[0]
        offset, length = struct.unpack_from("<QQ", data, at + 24)
        # SHT_NOBITS sections occupy no bytes in the file.
        kind = struct.unpack_from("<I", data, at + 4)[0]
        if kind != 8 and offset + length > len(data):
            raise ValueError("invalid ELF section extent")
        return name, data[offset:offset + length] if kind != 8 else b""

    _, strings = section(names)
    blobs = []
    for index in range(count):
        name, contents = section(index)
        end = strings.find(b"\0", name)
        if name >= len(strings) or end < 0:
            raise ValueError("invalid ELF section name")
        if strings[name:end] == b".nv_fatbin":
            blobs.append(contents)
    texts = []
    for blob in blobs:
        # Linked objects can concatenate several fatbins, with zero alignment padding.
        start = 0
        while start < len(blob):
            if not blob[start:].strip(b"\0"):
                break
            if len(blob) - start < 16:
                raise ValueError("truncated CUDA fatbin header")
            magic, _, header, length = struct.unpack_from("<IHHQ", blob, start)
            if magic != 0xBA55ED50 or header < 16 or header + length > len(blob) - start:
                raise ValueError("invalid CUDA fatbin header")
            at, end = start + header, start + header + length
            while at < end:
                if end - at < 20:
                    raise ValueError("truncated CUDA fatbin record")
                kind, _, entry_header, payload = struct.unpack_from("<HHIQ", blob, at)
                if entry_header < 20 or entry_header + payload > end - at:
                    raise ValueError("invalid CUDA fatbin record extent")
                compressed = struct.unpack_from("<I", blob, at + 16)[0]
                body = blob[at + entry_header:at + entry_header + payload]
                if kind == 1:
                    if compressed or b".version" not in body[:4096]:
                        raise ValueError("compressed/invalid PTX; rebuild with nvcc --no-compress")
                    texts.append(body.rstrip(b"\0").decode("utf-8"))
                at += entry_header + payload
            start = (end + 7) & ~7
    return texts


def _sources(source: Path):
    """Local quoted includes and PTX fixture paths; toolkit headers are identified by nvcc."""
    seen = set()
    def visit(path):
        path = path.resolve()
        if path in seen:
            return
        seen.add(path)
        for name in re.findall(r'"([^"\n]+\.(?:h|hpp|cuh|cu|ptx))"', path.read_text()):
            child = path.parent / name
            if child.is_file():
                visit(child)
    visit(source)
    return sorted(seen)


def build(output: Path, source: Path, argv: list[str]) -> int:
    """Execute exactly argv, and record immutable build inputs after success."""
    output, source = output.resolve(), source.resolve()
    sidecar = Path(str(output) + ".build.json")
    sidecar.unlink(missing_ok=True)  # stale metadata must not validate a failed rebuild
    cwd = Path.cwd()
    source_data = [(p, p.read_bytes()) for p in _sources(source)]
    version = subprocess.run([argv[0], "--version"], capture_output=True, text=True, check=True).stdout
    result = subprocess.run(argv)
    if result.returncode:
        return result.returncode
    if any(path.read_bytes() != data for path, data in source_data):
        raise ValueError("local source changed during compilation; rebuild before capture")
    store = output.parent / ".build-sources"
    store.mkdir(exist_ok=True)
    records = []
    for path, data in source_data:
        key = digest(data)
        (store / key).write_bytes(data)
        records.append({"path": str(path), "sha256": key, "bytes": len(data),
                        "asset": f".build-sources/{key}"})
    meta = {"schema": SCHEMA, "argv": argv, "cwd": str(cwd), "compiler": shutil.which(argv[0]),
            "nvcc_version": version, "source": str(source), "sources": records,
            "executable_sha256": digest(output.read_bytes())}
    sidecar.write_text(json.dumps(meta, indent=2) + "\n")
    return 0


def _archive_binary(binary: Path, target: Path, require_ptx: bool):
    meta = json.loads(Path(str(binary) + ".build.json").read_text())
    data = binary.read_bytes()
    if meta.get("schema") != SCHEMA or digest(data) != meta.get("executable_sha256"):
        raise ValueError(f"missing/stale build identity: {binary}")
    if not meta.get("argv") or not meta.get("nvcc_version") or not meta.get("sources"):
        raise ValueError(f"incomplete build record: {binary}")
    target.mkdir(parents=True, exist_ok=True)
    (target / "program").write_bytes(data)
    (target / "program").chmod(binary.stat().st_mode & 0o777)
    records = []
    for entry in meta["sources"]:
        asset = Path(entry["asset"])
        if asset.is_absolute() or ".." in asset.parts:
            raise ValueError("unsafe build source asset")
        contents = (binary.parent / asset).read_bytes()
        if digest(contents) != entry["sha256"] or len(contents) != entry["bytes"]:
            raise ValueError(f"changed build source artifact: {entry['path']}")
        dest = target / "sources" / entry["sha256"]
        dest.parent.mkdir(exist_ok=True)
        dest.write_bytes(contents)
        records.append({**entry, "asset": f"sources/{entry['sha256']}"})
    texts = extracted_ptx(binary)
    if require_ptx and not texts:
        raise ValueError(f"no embedded PTX in {binary}")
    ptx = []
    for index, text in enumerate(texts):
        filename = f"module-{index}.ptx"
        contents = text.encode()
        (target / filename).write_bytes(contents)
        ptx.append({"file": filename, "sha256": digest(contents), "bytes": len(contents)})
    meta = {**meta, "sources": records, "ptx": ptx, "executable": "program"}
    (target / "build.json").write_text(json.dumps(meta, indent=2) + "\n")
    return meta


def archive_probes(out: Path, suite: Path, binaries: Path, probes, *, mode: str) -> list[str]:
    """Archive each executed program once and every manifest case/argument. Return failures."""
    root = out / "probe-artifacts"
    root.mkdir(exist_ok=True)
    records, errors = [], []
    for program in dict.fromkeys(p.program for p in probes):
        try:
            native = binaries.name == "bin-native"
            ampere = binaries.name == "bin-ampere"
            needs_ptx = any(p.program == program and p.predict != "none" for p in probes)
            build_meta = _archive_binary(binaries / program, root / program / "executed", needs_ptx and not native and not ampere)
            relationship = "embedded PTX in the executed executable"
            if native:
                companion = _archive_binary(suite / "bin" / program, root / program / "ptx-companion", needs_ptx)
                signature = lambda meta: {(s["path"], s["sha256"]) for s in meta["sources"]}
                if signature(build_meta) != signature(companion) or build_meta["nvcc_version"] != companion["nvcc_version"]:
                    raise ValueError("native and PTX companion have different sources/compiler")
                relationship = ("native executable executed; separate PTX companion built from identical local sources "
                                "and nvcc version. This does not prove native compilation used this PTX.")
            elif ampere:
                relationship = "Ampere dry run only; not Blackwell differential evidence"
            records.append({"program": program, "relationship": relationship})
        except (OSError, ValueError, KeyError, TypeError, UnicodeError) as error:
            errors.append(f"{program}: {error}")
    manifest = (suite / "manifest.py").read_bytes()
    (root / "manifest.py").write_bytes(manifest)
    (root / "index.json").write_text(json.dumps({"schema": "warplens.probe-archive.v1", "mode": mode,
        "manifest_sha256": digest(manifest), "cases": [asdict(p) for p in probes],
        "programs": records, "errors": errors}, indent=2) + "\n")
    return errors


def validate_probe_archive(out: Path, expected_programs=None) -> list[str]:
    root = Path(out) / "probe-artifacts"
    errors = []
    try:
        index = json.loads((root / "index.json").read_text())
        if index.get("schema") != "warplens.probe-archive.v1":
            raise ValueError("invalid probe archive schema")
        if index.get("errors"):
            errors.extend(index["errors"])
        if digest((root / "manifest.py").read_bytes()) != index["manifest_sha256"]:
            errors.append("probe manifest integrity mismatch")
        programs = [r["program"] for r in index["programs"]]
        if expected_programs is not None and set(programs) != set(expected_programs):
            errors.append("missing or unexpected archived probe programs")
        for program in programs:
            path = Path(program)
            if path.is_absolute() or ".." in path.parts:
                raise ValueError("unsafe program artifact path")
            for folder in (root / program).iterdir():
                if not folder.is_dir():
                    continue
                meta = json.loads((folder / "build.json").read_text())
                if digest((folder / "program").read_bytes()) != meta["executable_sha256"]:
                    errors.append(f"{program}: executable integrity mismatch")
                embedded = extracted_ptx(folder / "program")
                if [digest(text.encode()) for text in embedded] != [p["sha256"] for p in meta["ptx"]]:
                    errors.append(f"{program}: archived PTX differs from the executable")
                needs_ptx = any(case["program"] == program and case["predict"] != "none" for case in index["cases"])
                relationship = next(r["relationship"] for r in index["programs"] if r["program"] == program)
                if needs_ptx and not embedded and (folder.name == "ptx-companion" or relationship.startswith("embedded")):
                    errors.append(f"{program}: missing required PTX")
                for entry in meta["sources"] + meta["ptx"]:
                    filename = Path(entry.get("asset", entry.get("file", "")))
                    if filename.is_absolute() or ".." in filename.parts:
                        raise ValueError("unsafe probe artifact path")
                    data = (folder / filename).read_bytes()
                    if len(data) != entry["bytes"] or digest(data) != entry["sha256"]:
                        errors.append(f"{program}: artifact integrity mismatch: {filename}")
            if not (root / program / "executed" / "build.json").is_file():
                errors.append(f"{program}: missing executed program")
            if "native executable" in next(r["relationship"] for r in index["programs"] if r["program"] == program):
                if not (root / program / "ptx-companion" / "build.json").is_file():
                    errors.append(f"{program}: missing native PTX companion")
    except (OSError, ValueError, KeyError, TypeError) as error:
        errors.append(f"incomplete probe provenance: {error}")
    return errors


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--source", type=Path, required=True)
    parser.add_argument("argv", nargs=argparse.REMAINDER)
    args = parser.parse_args()
    argv = args.argv[1:] if args.argv[:1] == ["--"] else args.argv
    if not argv:
        parser.error("missing compiler command after --")
    sys.exit(build(args.output, args.source, argv))
